def folded_map(rnd):
    # accordion-folded road map lying in the foreground, slightly rotated
    g = ['<g class="pl-map" transform="translate(470 352) rotate(-7)">']
    panels = 4
    pw, ph = 66, 104
    xs = [i * pw for i in range(panels + 1)]
    lift = [0, -7, 0, -7, 0]
    # panel faces
    for i in range(panels):
        a = (xs[i], lift[i])
        b = (xs[i + 1], lift[i + 1])
        c = (xs[i + 1], ph + lift[i + 1] * 0.4)
        d = (xs[i], ph + lift[i] * 0.4)
        cls = "pl-map-face" if i % 2 == 0 else "pl-map-face pl-map-face-shade"
        g.append(f'<path class="{cls}" d="{poly([a, b, c, d])}"/>')
    # street grid, clipped per panel by simple bounds
    grid = ""
    for i in range(panels):
        x0 = xs[i]
        for k in range(1, 6):
            yy = 12 + k * 15 + rnd.uniform(-2, 2)
            grid += f"M{n(x0 + 3)} {n(yy + lift[i] * (1 - k / 6))}L{n(x0 + pw - 3)} {n(yy + rnd.uniform(-3, 3) + lift[i + 1] * (1 - k / 6))}"
        for k in range(1, 4):
            xx = x0 + k * pw / 4 + rnd.uniform(-3, 3)
            grid += f"M{n(xx)} {n(8 + (lift[i] + lift[i + 1]) / 2)}L{n(xx + rnd.uniform(-4, 4))} {n(ph - 6)}"
    g.append(f'<path class="pl-line pl-hair" d="{grid}"/>')
    # river
    g.append(
        f'<path class="pl-water" d="{smooth([(0, 70), (40, 62), (80, 78), (130, 66), (190, 84), (264, 72)])}"/>'
    )
    # highway
    g.append(
        f'<path class="pl-hwy" d="{smooth([(0, 30), (60, 38), (120, 24), (190, 34), (264, 22)])}"/>'
    )
