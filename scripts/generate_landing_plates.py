def n(v):
    s = f"{v:.1f}"
    s = s.rstrip("0").rstrip(".") if "." in s else s
    return "0" if s in ("-0", "") else s


def poly(points, close=True):
    d = "M" + "L".join(f"{n(x)} {n(y)}" for x, y in points)
    return d + ("Z" if close else "")


def smooth(points, close=False, tension=1.0):
    """Catmull-Rom through points -> cubic bezier path."""
    pts = list(points)
    pts = [pts[-1], *pts, pts[0], pts[1]] if close else [pts[0], *pts, pts[-1]]
    d = f"M{n(pts[1][0])} {n(pts[1][1])}"
    for i in range(1, len(pts) - 2):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[i + 1], pts[i + 2]
        c1 = (
            p1[0] + (p2[0] - p0[0]) / 6 * tension,
            p1[1] + (p2[1] - p0[1]) / 6 * tension,
        )
        c2 = (
            p2[0] - (p3[0] - p1[0]) / 6 * tension,
            p2[1] - (p3[1] - p1[1]) / 6 * tension,
        )
        d += f"C{n(c1[0])} {n(c1[1])} {n(c2[0])} {n(c2[1])} {n(p2[0])} {n(p2[1])}"
    return d + ("Z" if close else "")


def fir(x, base, h, rnd, spread=0.3, lean=0.0):
    """Jagged conifer silhouette; returns (outline_path, highlight_strokes)."""
    tiers = max(4, int(h / 6.5))
    top = base - h
    trunk_h = max(2.0, h * 0.07)
    crown_bottom = base - trunk_h
    span = crown_bottom - top
    left, right, lights = [], [], []
    for i in range(tiers):
        t = (i + 1) / tiers
        y_tip = top + span * t + rnd.uniform(-0.6, 1.2)
        half = spread * h * (t**0.92) * rnd.uniform(0.82, 1.12)
        notch_y = y_tip - span / tiers * rnd.uniform(0.45, 0.7)
        shift = lean * (1 - t) * h
        cx = x + shift
        left += [(cx - half * rnd.uniform(0.3, 0.45), notch_y), (cx - half, y_tip)]
        right += [
            (cx + half * rnd.uniform(0.3, 0.45), notch_y),
            (cx + half * rnd.uniform(0.86, 1.08), y_tip),
        ]
        if h > 36 and i > 0 and rnd.random() < 0.8:
            lx = cx - half * rnd.uniform(0.35, 0.7)
            lights.append(
                f"M{n(lx)} {n(y_tip - 1.2)}l{n(half * 0.22)} {n(-span / tiers * 0.5)}"
            )
    tw = max(0.9, h * 0.022)
    pts = [
        (x + lean * h, top),
        *right,
        (x + tw, crown_bottom),
        (x + tw, base),
        (x - tw, base),
        (x - tw, crown_bottom),
        *left[::-1],
    ]
    return poly(pts), "".join(lights)


def tuft(x, y, s, rnd):
    d = ""
    k = rnd.randint(3, 6)
    for _i in range(k):
        a = -math.pi / 2 + rnd.uniform(-0.75, 0.75)
        L = s * rnd.uniform(0.5, 1.0)
        ex, ey = (
            x + math.cos(a) * L + rnd.uniform(-0.6, 0.6) * s * 0.2,
            y + math.sin(a) * L,
        )
        mx, my = x + math.cos(a) * L * 0.5 + (ex - x) * 0.15, y + math.sin(a) * L * 0.6
        d += f"M{n(x + rnd.uniform(-1.2, 1.2))} {n(y)}Q{n(mx)} {n(my)} {n(ex)} {n(ey)}"
    return d


