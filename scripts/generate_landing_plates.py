def _range(ridge, base, rnd, caps=(), hatch="pl-hatch", gully=True, fade=0.72):
    out = []
    sil = [*ridge, (ridge[-1][0], base), (ridge[0][0], base)]
    out.append(f'<path class="pl-paper" d="{poly(sil)}"/>')
    shade = []
    peaks = []
    for i in range(1, len(ridge) - 1):
        px, py = ridge[i]
        if py < ridge[i - 1][1] and py < ridge[i + 1][1]:
            peaks.append((px, py))
            j = i + 1
            while j + 1 < len(ridge) and ridge[j + 1][1] > ridge[j][1]:
                j += 1
            vx, vy = ridge[j]
            depth = (base - py) * fade
            low = (px + (vx - px) * rnd.uniform(0.05, 0.2), py + depth)
            mid = (vx - (vx - px) * 0.1, vy + (base - vy) * 0.35)
            shade.append(poly([(px, py), *ridge[i + 1 : j + 1], mid, low]))
    out.append(f'<path class="{hatch}" d="{"".join(shade)}"/>')
    cap_paths = []
    for px, py in peaks:
        if (px, py) not in caps:
            continue
        dep = (base - py) * 0.24
        pts = [(px, py)]
        k = 7
        for s in range(1, k):
            t = s / k
            xx = px - dep * 0.35 + t * dep * 1.3
            yy = (
                py
                + dep * (0.35 + 0.65 * math.sin(t * math.pi))
                + rnd.uniform(-2.5, 2.5)
            )
            pts.append((xx, yy))
        pts.append((px + dep * 0.9, py + dep * 0.55))
        cap_paths.append(poly(pts))
    if cap_paths:
        out.append(f'<path class="pl-paper" d="{"".join(cap_paths)}"/>')
    out.append(f'<path class="pl-line pl-med" d="{poly(ridge, close=False)}"/>')
    if gully:
        g = ""
        for px, py in peaks:
            for _ in range(rnd.randint(2, 4)):
                L = (base - py) * rnd.uniform(0.16, 0.38)
                a = math.radians(rnd.uniform(60, 120))
                sx = px + rnd.uniform(-8, 6)
                sy = py + rnd.uniform(3, 12)
                g += f"M{n(sx)} {n(sy)}q{n(math.cos(a) * L * 0.4)} {n(L * 0.5)} {n(math.cos(a) * L)} {n(L)}"
        out.append(f'<path class="pl-line pl-hair" d="{g}"/>')
    return "".join(out)


