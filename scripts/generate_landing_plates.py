def plate_map():
    """An opened accordion road map with a route and a position pin."""
    rnd = random.Random(5)
    # three panels in loose perspective: top edge rises to the right
    P = [(18, 56), (84, 34), (150, 48), (214, 22)]
    B = [(34, 150), (98, 132), (160, 146), (222, 120)]
    out = ['<g class="plate-ink">']
    out.append(
        f'<path class="pl-shadow" d="{poly([(30, 154), (100, 138), (164, 152), (228, 126), (232, 130), (166, 158), (100, 144), (32, 160)])}"/>'
    )
    for i in range(3):
        cls = "pl-map-face" if i != 1 else "pl-map-face pl-map-face-shade"
        out.append(
            f'<path class="{cls}" d="{poly([P[i], P[i + 1], B[i + 1], B[i]])}"/>'
        )

    def lerp(a, b, t):
        return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)

    def at(u, v):
        """u in 0..3 across panels, v in 0..1 down."""
        i = min(2, int(u))
        t = u - i
        top = lerp(P[i], P[i + 1], t)
        bot = lerp(B[i], B[i + 1], t)
        return lerp(top, bot, v)

    grid = ""
    for k in range(1, 9):
        v = k / 9
        pts = [at(u / 6, v) for u in range(19)]
        grid += poly(pts, close=False)
    for k in range(1, 12):
        u = k / 4
        grid += poly([at(u, 0.04), at(u + rnd.uniform(-0.05, 0.05), 0.96)], close=False)
    out.append(f'<path class="pl-line pl-hair" d="{grid}"/>')
    # a park block and a lake
    out.append(
        f'<path class="pl-hatch-dense" d="{poly([at(0.5, 0.56), at(0.75, 0.56), at(0.75, 0.78), at(0.5, 0.78)])}"/>'
    )
    out.append(
        f'<path class="pl-water-fill" d="{smooth([at(2.2, 0.62), at(2.55, 0.55), at(2.75, 0.7), at(2.5, 0.84), at(2.2, 0.62)])}"/>'
    )
    # river and highway
    out.append(
        f'<path class="pl-water" d="{smooth([at(0, 0.3), at(0.6, 0.38), at(1.2, 0.26), at(1.9, 0.4), at(2.99, 0.3)])}"/>'
    )
    out.append(
        f'<path class="pl-hwy" d="{smooth([at(0.02, 0.9), at(0.9, 0.7), at(1.6, 0.74), at(2.3, 0.46), at(2.98, 0.16)])}"/>'
    )
    # route
    out.append(
        f'<path class="pl-route pl-route-solid" d="{smooth([at(0.25, 0.2), at(0.6, 0.45), at(1.1, 0.5), at(1.45, 0.62), at(1.9, 0.58), at(2.2, 0.32)])}"/>'
    )
    # creases
    out.append(
        f'<path class="pl-line pl-thin" d="M{n(P[1][0])} {n(P[1][1])}L{n(B[1][0])} {n(B[1][1])}M{n(P[2][0])} {n(P[2][1])}L{n(B[2][0])} {n(B[2][1])}"/>'
    )
    # position pin
    px, py = at(2.2, 0.32)
    out.append(
        f'<path class="pl-pin" d="M{n(px)} {n(py)}c-2-6-8-10-8-16a8 8 0 0 1 16 0c0 6-6 10-8 16Z"/>'
        f'<circle class="pl-paper pl-line pl-thin" cx="{n(px)}" cy="{n(py - 16)}" r="3.2"/>'
    )
    out.append("</g>")
    return f'<svg class="plate plate-action" viewBox="0 0 240 170" aria-hidden="true" focusable="false">{"".join(out)}</svg>'


def plate_pencil():
    """A pencil tracing an undriven route across a street grid."""
    rnd = random.Random(8)
    out = ['<g class="plate-ink">']
    # street grid sketched loosely; undriven streets dashed
    grid, undriven = "", ""
    xs = [20, 58, 96, 134, 172, 210]
    ys = [26, 58, 90, 122, 150]
    for y in ys:
        for j in range(len(xs) - 1):
            seg = f"M{xs[j]} {y + rnd.uniform(-1, 1):.1f}L{xs[j + 1]} {y + rnd.uniform(-1, 1):.1f}"
            if rnd.random() < 0.38:
                undriven += seg
            else:
                grid += seg
    for x in xs:
        for i in range(len(ys) - 1):
            seg = f"M{x + rnd.uniform(-1, 1):.1f} {ys[i]}L{x + rnd.uniform(-1, 1):.1f} {ys[i + 1]}"
            if rnd.random() < 0.38:
                undriven += seg
            else:
                grid += seg
    out.append(f'<path class="pl-line pl-thin" d="{grid}"/>')
    out.append(f'<path class="pl-line pl-thin pl-undriven" d="{undriven}"/>')
    # a block of hatching (a park) and a diagonal avenue
    out.append('<path class="pl-hatch-dense" d="M100 94h30v24h-30Z"/>')
    out.append('<path class="pl-line pl-med" d="M14 150C60 128 104 70 216 20"/>')
    # traced route in rust ending at the pencil tip
    route = "M20 150L58 150L58 122L96 122L96 90L134 90"
    out.append(f'<path class="pl-route pl-route-solid" d="{route}"/>')
    out.append('<circle class="pl-route-start" cx="20" cy="150" r="3.2"/>')
    # pencil, tip at (152, 58), body running up and to the right
    ang = math.radians(-33)
    ux, uy = math.cos(ang), math.sin(ang)
    vx, vy = -uy, ux
    tip = (134, 90)

    def pt(a, b):
        return (tip[0] + ux * a + vx * b, tip[1] + uy * a + vy * b)

    w = 5.2
    lead = [tip, pt(8, -1.6), pt(8, 1.6)]
    cone = [tip, pt(20, -w), pt(20, w)]
    body = [pt(20, -w), pt(88, -w), pt(88, w), pt(20, w)]
    ferrule = [pt(88, -w - 0.4), pt(100, -w - 0.4), pt(100, w + 0.4), pt(88, w + 0.4)]
    eraser = [
        pt(100, -w + 0.2),
        pt(110, -w + 0.2),
        pt(112, -w + 2),
        pt(112, w - 2),
        pt(110, w - 0.2),
        pt(100, w - 0.2),
    ]

    def sh(a, b):
        x, y = pt(a, b)
        return (x + 3, y + 7)

    out.append(
        f'<path class="pl-shadow" d="{poly([sh(4, 0), sh(112, -w + 1), sh(112, w - 1)])}"/>'
    )
    out.append(f'<path class="pl-wood pl-line pl-thin" d="{poly(cone)}"/>')
    out.append(f'<path class="pl-solid" d="{poly(lead)}"/>')
    out.append(f'<path class="pl-pencil pl-line pl-thin" d="{poly(body)}"/>')
    facets = poly([pt(22, -1.7), pt(88, -1.7)], close=False) + poly(
        [pt(22, 1.7), pt(88, 1.7)], close=False
    )
    out.append(f'<path class="pl-line pl-hair" d="{facets}"/>')
    # scalloped cone edge
    scal = "".join(
        f"M{n(pt(20, s)[0])} {n(pt(20, s)[1])}Q{n(pt(17.5, s + 1.3)[0])} {n(pt(17.5, s + 1.3)[1])} {n(pt(20, s + 2.6)[0])} {n(pt(20, s + 2.6)[1])}"
        for s in (-5.2, -2.6, 0, 2.6)
    )
    out.append(f'<path class="pl-line pl-hair" d="{scal}"/>')
    out.append(f'<path class="pl-ferrule pl-line pl-thin" d="{poly(ferrule)}"/>')
    ribs = "".join(
        poly([pt(a, -w - 0.4), pt(a, w + 0.4)], close=False) for a in (91, 94, 97)
    )
    out.append(f'<path class="pl-line pl-hair" d="{ribs}"/>')
    out.append(f'<path class="pl-eraser pl-line pl-thin" d="{poly(eraser)}"/>')
    out.append("</g>")
    return f'<svg class="plate plate-action" viewBox="0 0 240 170" aria-hidden="true" focusable="false">{"".join(out)}</svg>'


